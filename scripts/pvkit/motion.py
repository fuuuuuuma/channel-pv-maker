def load():
    rows = []
    for ln in (D / 'catalog.tsv').read_text(encoding='utf-8').splitlines():
        if not ln or ln.startswith('#') or ln.startswith('id\t'):
            continue
        c = ln.split('\t')
        if len(c) >= 6:
            rows.append(dict(id=c[0], pack=c[1], cat=c[2], title=c[3], tags=c[4], summary=c[5]))
    return rows


def search(words, n=8):
    rows = load()
    by = {r['id']: r for r in rows}
    score = {}
    text = ' '.join(words)
    for key, ids in ALIAS.items():
        if key in text:
            for rank, i in enumerate(ids):
                score[i] = score.get(i, 0) + 6 - rank
    for w in words:
        wl = w.lower()
        for r in rows:
            if w in r['title'] or wl in r['title'].lower():
                score[r['id']] = score.get(r['id'], 0) + 4
            if w in r['summary']:
                score[r['id']] = score.get(r['id'], 0) + 2
            if wl in r['tags'].lower().split(','):
                score[r['id']] = score.get(r['id'], 0) + 2
    best = sorted(score.items(), key=lambda kv: (-kv[1], kv[0]))[:n]
    return [by[i] for i, _ in best if i in by]


def prompt(i):
    p = D / 'prompts' / f'{int(i):03d}.txt'
    return p.read_text(encoding='utf-8') if p.exists() else None


def main(args, list_pack=None):
    if list_pack:
        for r in load():
            if r['pack'] == list_pack:
                print(f"#{r['id']}  {r['title']}  … {r['summary']}")
        return 0
    if len(args) == 1 and re.fullmatch(r'#?\d{1,3}', args[0]):
        t = prompt(args[0].lstrip('#'))
        if not t:
            print('その番号はありません（001〜144）')
            return 1
        print(t)
        return 0
    hits = search(args)
    if not hits:
        print('当てはまる名前が見つかりませんでした。references/motion.md の早見表か `pv.py motion --list camera` を見てください。')
        return 1
    for r in hits:
        print(f"#{r['id']}  {r['title']}  [{r['cat']}]\n      {r['summary']}")
    print(f"\n頼み方の全文: pv.py motion <番号>（{D.relative_to(D.parents[3])}/prompts/NNN.txt）")
    print('Motion Prompt · MIT License · 作者 大滝昇平 · https://showheyohtaki.github.io/motion-prompt/')
    return 0
